"""Describe the amended continuation without hiding historical generation costs.

The generation protocol is unchanged. A post-failure amendment records an
output-cap-truncated invalid JSON response as ineligible, without repair/retry.
"""

import copy

from . import analysis as original_analysis


def _truncations(records):
    return sum(record.get("output_truncation_failure") is True for record in records)


def summarize(manifest, initial_panel, answers):
    """Keep all 480 revision outcomes, separating 146 historical and 334 new calls."""
    imported_count = manifest.get("imported_revision_calls")
    if type(imported_count) is not int or imported_count != 146:
        raise ValueError("This continuation requires the frozen 146-call imported prefix")
    if len(answers) != 480 or any(record.get("call_index") != index for index, record in enumerate(answers)):
        raise ValueError("Continuation analysis requires all 480 revision answers in canonical call order")

    imported, generated = answers[:imported_count], answers[imported_count:]
    result = original_analysis.summarize(manifest, initial_panel, answers)
    result["total_revision_calls"] = result.pop("new_calls")
    result["all_revision_generation_cost"] = result.pop("new_generation_cost")
    result["imported_revision_calls"] = imported_count
    result["imported_previously_evaluated_answers"] = manifest.get("imported_answer_calls", 145)
    result["imported_locally_evaluated_truncated_answers"] = imported_count - result["imported_previously_evaluated_answers"]
    result["new_calls"] = len(generated)
    result["physical_unique_model_calls_including_initial"] = len(initial_panel) + len(answers)
    result["imported_revision_generation_cost"] = original_analysis._cost(imported)
    result["new_generation_cost"] = original_analysis._cost(generated)
    result["source_run_snapshot"] = copy.deepcopy(manifest["source_run_snapshot"])
    result["protocol_amendment"] = {
        "post_failure": True,
        "generation_protocol_changed": False,
        "response_repair": False,
        "response_retry": False,
        "policy": "Only invalid JSON returned at the unchanged 1024-token length stop becomes one ineligible response; other schema violations remain fatal.",
        "source_status": "failed_original_v1_preserved",
        "imported_raw_generations": imported_count,
        "previously_evaluated_imported_answers": result["imported_previously_evaluated_answers"],
    }
    result["output_truncation_failures"] = {
        "total": _truncations(answers),
        "imported": _truncations(imported),
        "new": _truncations(generated),
        "by_arm": {},
    }
    for arm in original_analysis.ARMS:
        arm_data = result["arms"][arm]
        imported_arm = [record for record in imported if record["arm"] == arm]
        generated_arm = [record for record in generated if record["arm"] == arm]
        arm_data["all_revision_generation_cost"] = arm_data.pop("new_generation_cost")
        arm_data["imported_revision_generation_cost"] = original_analysis._cost(imported_arm)
        arm_data["new_generation_cost"] = original_analysis._cost(generated_arm)
        result["output_truncation_failures"]["by_arm"][arm] = {
            "total": _truncations(imported_arm + generated_arm),
            "imported": _truncations(imported_arm),
            "new": _truncations(generated_arm),
            "by_round": {
                str(round_index): _truncations([record for record in imported_arm + generated_arm
                                               if record["round"] == round_index])
                for round_index in (1, 2, 3)
            },
        }
    result["notes"].extend([
        "This is a post-failure protocol amendment, not a completed run under the original v1 stopping policy.",
        "The original failed v1 evidence is preserved. Its 146 raw generations are reused; 145 previous evaluations are unchanged and the truncated response is evaluated locally without another model call.",
        "new_calls and new_generation_cost describe only the 334 requests generated by this continuation; total_revision_calls and all_revision_generation_cost include all 480 revision outcomes.",
        "Both trajectories include the same 80 historical initial calls and their respective historical imported revisions. Physical unique cost counts each of the 560 initial/revision generations once across runs.",
        "A length-truncated invalid JSON response contributes one ineligible outcome, including its original token and request-duration costs. Its unmodified raw text is not repaired or forwarded as a complete explanation.",
        "The observed failure motivated this amendment; findings remain exploratory, with the same round-3 comparison and no new round selection or hidden-reasoning grading.",
    ])
    return result
